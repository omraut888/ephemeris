//! The TypeScript schema types must match the Rust ones (docs/phase2-design.md
//! §3). This renders every type's declaration with ts-rs and compares it with
//! the committed `web/src/schema.gen.ts`; any change to a schema type that is
//! not regenerated fails here. Regenerate with
//! `UPDATE_TS=1 cargo test -p ephemeris-wasm --test ts_types`.

#![cfg(not(target_arch = "wasm32"))]

use std::path::Path;

use ephemeris_core::pipeline::{ForecastOptions, SimMode, SimulateOptions};
use ephemeris_core::schema::Date as IsoDate;
use ephemeris_core::schema::{
    BillReport, ChangeChannel, ConeDay, ConeReport, CycleBasisReport, CycleLowReport,
    CycleLowsReport, Estimate, Feed, FeedTransaction, ForecastReport, IncomeReport, MonthlyOn,
    PayCadence, RegimeChange, Shift, TargetReport,
};
use ephemeris_core::{FlowKind, TxnStatus};
use ts_rs::{Config, TS};

const HEADER: &str = "\
// GENERATED by crates/ephemeris-wasm/tests/ts_types.rs from the Rust schema
// types (ts-rs). Do not edit: change the Rust types, then run
//   UPDATE_TS=1 cargo test -p ephemeris-wasm --test ts_types
// Dates are `IsoDate`, a `YYYY-MM-DD` string. Integer ids and seeds are
// `number`: ids are below 2^53 and seeds from the app are too. Every options
// field has a default on the Rust side, so callers may pass a `Partial<>`.
";

fn generated() -> String {
    let cfg = Config::default();
    let decls = [
        IsoDate::decl(&cfg),
        // Feed (in).
        Feed::decl(&cfg),
        FeedTransaction::decl(&cfg),
        FlowKind::decl(&cfg),
        TxnStatus::decl(&cfg),
        // Report (out).
        ForecastReport::decl(&cfg),
        Estimate::decl(&cfg),
        IncomeReport::decl(&cfg),
        PayCadence::decl(&cfg),
        BillReport::decl(&cfg),
        MonthlyOn::decl(&cfg),
        Shift::decl(&cfg),
        RegimeChange::decl(&cfg),
        ChangeChannel::decl(&cfg),
        ConeReport::decl(&cfg),
        ConeDay::decl(&cfg),
        TargetReport::decl(&cfg),
        CycleLowsReport::decl(&cfg),
        CycleLowReport::decl(&cfg),
        CycleBasisReport::decl(&cfg),
        // Options for the WASM calls.
        SimulateOptions::decl(&cfg),
        SimMode::decl(&cfg),
        ForecastOptions::decl(&cfg),
    ];
    let mut out = String::from(HEADER);
    for d in decls {
        out.push_str("\nexport ");
        out.push_str(&d);
        out.push('\n');
    }
    out
}

#[test]
fn typescript_schema_is_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../web/src/schema.gen.ts");
    let actual = generated();
    if std::env::var_os("UPDATE_TS").is_some() {
        std::fs::write(&path, &actual).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == actual,
        "{} is out of date with the Rust schema; run \
         UPDATE_TS=1 cargo test -p ephemeris-wasm --test ts_types",
        path.display()
    );
}
